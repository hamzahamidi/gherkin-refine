import { execFileSync } from "node:child_process";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const outputDirectory = join(root, "docs/rules");
const check = process.argv.includes("--check");

const { rules } = JSON.parse(execFileSync(process.execPath, [join(root, "dist/cli.js"), "--list-rules", "--format", "json"], { encoding: "utf8" }));
const overview = await readFile(join(root, "docs/rules.md"), "utf8");
const behavior = new Map();
for (const line of overview.split("\n")) {
  const match = line.match(/^\| \[`([a-z0-9-]+)`\]\(rules\/[a-z0-9-]+\.md\) \| [^|]+ \| [^|]+ \| (.+) \|$/);
  if (match) behavior.set(match[1], match[2]);
}

const pages = new Map();
for (const rule of rules) {
  const text = behavior.get(rule.id);
  if (!text) throw new Error(`docs/rules.md has no linked row for ${rule.id}.`);
  const hasOptions = rule.defaultOptions !== undefined && !(typeof rule.defaultOptions === "object" && Object.keys(rule.defaultOptions).length === 0);
  const setting = hasOptions ? `["error", ${JSON.stringify(rule.defaultOptions)}]` : `"error"`;
  pages.set(`${rule.id}.md`, [
    "<!-- Generated by scripts/generate-rule-docs.mjs from rule metadata and docs/rules.md. Run npm run docs:rules after changing either. -->",
    "",
    `# ${rule.id}`,
    "",
    rule.description,
    "",
    "| Category | Recommended | Safe autofix | Default options |",
    "| --- | --- | --- | --- |",
    `| ${rule.category} | ${rule.recommended ? "yes" : "no"} | ${rule.fixable ? "yes" : "no"} | ${hasOptions ? `\`${JSON.stringify(rule.defaultOptions)}\`` : "none"} |`,
    "",
    /[.!?]$/.test(text) ? text : `${text}.`,
    "",
    "## Configuration",
    "",
    "```json",
    `{ "rules": { "${rule.id}": ${setting} } }`,
    "```",
    ...(rule.examples?.length ? ["", "## Triggered by", "", ...rule.examples.flatMap((example) => ["```text", example, "```"])] : []),
    ""
  ].join("\n"));
}

if (check) {
  const existing = new Set((await readdir(outputDirectory).catch(() => [])).filter((name) => name.endsWith(".md")));
  const stale = [...pages.keys()].filter((name) => !existing.has(name));
  for (const [name, content] of pages) {
    if (existing.has(name) && (await readFile(join(outputDirectory, name), "utf8")) !== content) stale.push(name);
  }
  stale.push(...[...existing].filter((name) => !pages.has(name)));
  if (stale.length > 0) {
    console.error(`Rule pages are out of date: ${stale.join(", ")}. Run npm run docs:rules.`);
    process.exit(1);
  }
} else {
  await rm(outputDirectory, { recursive: true, force: true });
  await mkdir(outputDirectory, { recursive: true });
  for (const [name, content] of pages) await writeFile(join(outputDirectory, name), content);
  console.log(`Wrote ${pages.size} rule pages to docs/rules.`);
}
